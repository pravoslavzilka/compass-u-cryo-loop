"""Compare PF working scenarios for 3 power-limit configs -> docs/pf/power_limit_comparison.md"""
import sys, os, re, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from matlib import Result
D = 'data/PF'
SC = ['3100-rev15','4300-rev18','5400-rev18','24300-rev28']
full = lambda s: s + '-ver_vacuum-rrr30-77K-rump50kAs-1'
CFG = [('Off (no limit)', lambda s: f'{D}/working_scenarios_noPowerOpt/{full(s)}'),
       ('Valve (PF_RV01)', lambda s: next(p for p in (f'{D}/working_scenarios/{full(s)}', f'{D}/working_scenarios_oneCellEvap_10m/{full(s)}') if os.path.isdir(p))),
       ('Speed (C-SPEED-b)', lambda s: f'{D}/working_scenarios_speedPowerLimit/{full(s)}')]
coils = ['PF1U','PF1L','PF2U','PF2L','PF3U','PF3L','PF4U','PF4L']
def first_le(a, t, thr):   # first time hot wall stays <= thr
    k = np.where(a > thr)[0]
    if not len(k): return 0.0
    return float(t[k[-1]+1]) if k[-1] < len(t)-1 else float('nan')
rows = []
for s in SC:
    for name, f in CFG:
        p = f(s); r = Result(f'{p}/{full(s)}.mat'); t = r.time; g = r.get
        Tw = np.array([np.max([g(n) for n in r.names if re.match(rf'^{c}\.tube\d\.heatPort\[\d+\]\.T$', n)], axis=0) for c in coils])
        hot = Tw.max(0); P = g('fan2ndOrder.P_shaft')/1e3; Ph = g('fan2ndOrder.P_hyd')/1e3
        m = g('sensor_m_flow.sensorValueSI') if r.has('sensor_m_flow.sensorValueSI') else g('sensor_m_flow.sensorValue')
        mf = g('fan2ndOrder.summary.m_flow_gas_A'); rv = np.abs(g('PF_RV01.portA.m_flow'))
        sup = g('sensor_T.sensorValue'); T = t[-1]
        t81 = first_le(hot, t, 81.0); t80 = first_le(hot, t, 80.0)
        E = np.trapezoid(P, t)/3600
        i81 = np.searchsorted(t, t81) if t81 == t81 else len(t)-1
        E81 = np.trapezoid(P[:i81+1], t[:i81+1])/3600
        mean = lambda a: np.trapezoid(a, t)/T
        rows.append(dict(sc=s, cfg=name, t81=t81, t80=t80, hotend=hot[-1], sup=sup.min(),
            Pmean=mean(P), Ppk=P.max(), Pend=P[-1], over=100*np.trapezoid((P>50.5).astype(float), t)/T, E=E, E81=E81,
            eta=np.trapezoid(Ph, t)/np.trapezoid(P, t), m=mean(mf-rv), mf=mean(mf), rv=mean(rv), rpm=mean(g('fan2ndOrder.summary.speed_rpm')), T=T))
f = lambda x, d=0: 'n/a' if x != x else f'{x:.{d}f}'
H = ['Config','Hot wall\n<=81 K [s]','<=80 K [s]','End hot\nwall [K]','Min supply\n[K]','P mean/peak/end\n[kW]','Time\n>50.5 kW','Energy\n[kWh]','E to 81 K\n[kWh]','eta','m_coils/m_fan/m_RV01\n[kg/s]','Mean rpm']
def line(x): return [x['cfg'], f(x['t81']), f(x['t80']), f"{x['hotend']:.1f}", f"{x['sup']:.1f}", f"{x['Pmean']:.1f} / {x['Ppk']:.1f} / {x['Pend']:.1f}", f"{x['over']:.0f} %", f"{x['E']:.1f}", f"{x['E81']:.1f}", f"{x['eta']:.2f}", f"{x['m']:.2f} / {x['mf']:.2f} / {x['rv']:.2f}", f"{x['rpm']:.0f}"]
out = ['# PF working scenarios: power-limit configurations compared', '',
 'Same model, old one-cell 10 m evaporator, other algorithms on; only the circulator power limiting differs. Generated by `tools/scenarios/compare_pf_algos.py`; image: `power_limit_comparison.png`.', '',
 '- **Off**: `enableCirculatorPowerOptimization=false`, fan at fixed 200 Hz.', '- **Valve**: PF_RV01 bypass PI limits shaft power.', '- **Speed**: C-SPEED-b, PI on shaft power trims circulator speed (RV01 off).', '',
 'Hot wall <=81 K = time after which the hottest coil wall stays below 81 K. eta = mean hydraulic/shaft power. m_coils = m_fan - m_RV01. E to 81 K = circulator energy until then.', '']
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
fig, axs = plt.subplots(len(SC), 1, figsize=(17, 2.5*len(SC)))
for ax, sc in zip(axs, SC):
    rs = [x for x in rows if x['sc'] == sc]
    out += [f'## {sc}', '', '| '+' | '.join(h.replace('\n',' ') for h in H)+' |', '|'+'---|'*len(H)] + ['| '+' | '.join(line(x))+' |' for x in rs] + ['']
    ax.axis('off'); ax.set_title(sc, loc='left', fontweight='bold')
    tb = ax.table(cellText=[line(x) for x in rs], colLabels=H, loc='center', cellLoc='center'); tb.auto_set_font_size(False); tb.set_fontsize(9); tb.scale(1, 1.9)
    for j in range(len(H)): tb[0, j].set_facecolor('#dde6f0'); tb[0, j].set_height(0.30)
    for r_, col in zip((1, 2, 3), ('#f4f4f4', '#fff0e0', '#e4f4e4')):
        for j in range(len(H)): tb[r_, j].set_facecolor(col)
fig.tight_layout(); fig.savefig('docs/pf/power_limit_comparison.png', dpi=130)
open('docs/pf/power_limit_comparison.md','w').write('\n'.join(out)+'\n')
